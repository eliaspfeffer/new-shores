import assert from 'node:assert/strict';
import {parseSave} from '../src/savegames.js';
const data={version:6,resources:{wood:2},buildings:[{type:'storehouse',x:25,y:25,progress:1}],roads:[],workers:[{id:1,x:25.5,y:26.5,taskIndex:-1,employerIndex:0}]};
const types=['storehouse'];assert.equal(parseSave(JSON.stringify(data),types).resources.wood,2);
const expanded={...data,worldSize:72,terrain:Array.from({length:72},()=>Array(72).fill('water'))};assert.equal(parseSave(JSON.stringify(expanded),types).worldSize,72);
assert.throws(()=>parseSave(JSON.stringify({...data,worldSize:64}),types));
assert.throws(()=>parseSave(JSON.stringify({...data,version:10}),types));
assert.throws(()=>parseSave(JSON.stringify({...data,workers:[{...data.workers[0],employerIndex:8}]}),types));
assert.throws(()=>parseSave(JSON.stringify({...data,workers:[...data.workers,...data.workers]}),types));
assert.throws(()=>parseSave(JSON.stringify({...data,resources:{wood:-1}}),types));
assert.throws(()=>parseSave(JSON.stringify({...data,resources:{'<img src=x>':1}}),types));
assert.throws(()=>parseSave('{"__proto__":{}}',types));
console.log('PASS: save parsing, version rejection, bounds/references, duplicate IDs and unsafe keys');
const forgeSave={...data,buildings:[...data.buildings,{type:'toolsmith',x:24,y:25,progress:1,toolOrderMode:true,toolOrders:{shovel:5}}]};
assert.equal(parseSave(JSON.stringify(forgeSave),['storehouse','toolsmith']).buildings[1].toolOrders.shovel,5);
for(const invalid of [{shovel:-1},{shovel:1000},{unknown:1}])assert.throws(()=>parseSave(JSON.stringify({...forgeSave,buildings:[data.buildings[0],{...forgeSave.buildings[1],toolOrders:invalid}]}),['storehouse','toolsmith']));
console.log('PASS: tool order save/load and invalid order rejection');
